#!/usr/bin/env node
// Issue, revoke and check training certificates for the /verify page.
//
// Records are stored in snippets/certificate-registry.jsx. Each record is
// encrypted with a key derived from its certificate number, so the published
// registry does not list participant names. A record can only be read by
// someone who already has its certificate number.
//
// Usage:
//   node scripts/certificates.mjs add --name "Juan Dela Cruz" --course "Course name" --completed 2026-11-01 [--id U7K-XXXX-XXXX-XXXX]
//   node scripts/certificates.mjs import <roster.csv>      (columns: name,course,completed[,id])
//   node scripts/certificates.mjs revoke --id <certificate no.>
//   node scripts/certificates.mjs check --id <certificate no.>
//   node scripts/certificates.mjs count
//   node scripts/certificates.mjs init                     (first run only)
//
// Options:
//   --prefix <text>     Prefix for new certificate numbers (default U7K)
//   --base-url <url>    Site URL used when printing verification links
//                       (or set CERT_VERIFY_BASE_URL)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve, relative, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";
import { pbkdf2Sync, hkdfSync, randomBytes, randomInt, createCipheriv, createDecipheriv } from "node:crypto";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REGISTRY_PATH = join(ROOT, "snippets", "certificate-registry.jsx");
const ITERATIONS = 210000;
const CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
const HEADER =
  "// Generated by scripts/certificates.mjs. Do not edit by hand.\n" +
  "// Each record is encrypted with its certificate number. See /verify.\n";

const fail = (message) => {
  console.error(`error: ${message}`);
  process.exit(1);
};

const parseArgs = (argv) => {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg.startsWith("--")) {
      const key = arg.slice(2);
      const next = argv[i + 1];
      if (next === undefined || next.startsWith("--")) out[key] = true;
      else {
        out[key] = next;
        i++;
      }
    } else out._.push(arg);
  }
  return out;
};

const normalize = (value) => String(value || "").toUpperCase().replace(/[^A-Z0-9]/g, "");

const loadRegistry = () => {
  if (!existsSync(REGISTRY_PATH)) {
    return { version: 1, kdf: { name: "PBKDF2-SHA256", iterations: ITERATIONS, salt: randomBytes(16).toString("base64") }, records: {} };
  }
  const text = readFileSync(REGISTRY_PATH, "utf8");
  const match = text.match(/export const certificateRegistry = (\{[\s\S]*\});\s*$/);
  if (!match) fail(`can't read ${relative(ROOT, REGISTRY_PATH)}`);
  return JSON.parse(match[1]);
};

const saveRegistry = (registry) => {
  const sorted = Object.fromEntries(Object.entries(registry.records).sort(([a], [b]) => a.localeCompare(b)));
  const body = JSON.stringify({ ...registry, records: sorted }, null, 2);
  writeFileSync(REGISTRY_PATH, `${HEADER}\nexport const certificateRegistry = ${body};\n`);
};

const deriveKeys = (registry, certNo) => {
  const normalized = normalize(certNo);
  if (normalized.length < 6) fail(`certificate number "${certNo}" is too short`);
  const master = pbkdf2Sync(Buffer.from(normalized), Buffer.from(registry.kdf.salt, "base64"), registry.kdf.iterations, 32, "sha256");
  const lookupId = Buffer.from(hkdfSync("sha256", master, Buffer.alloc(0), "cert-lookup", 16)).toString("hex");
  const key = Buffer.from(hkdfSync("sha256", master, Buffer.alloc(0), "cert-record", 32));
  return { lookupId, key };
};

const encrypt = (key, lookupId, details) => {
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  cipher.setAAD(Buffer.from(lookupId));
  const data = Buffer.concat([cipher.update(JSON.stringify(details), "utf8"), cipher.final(), cipher.getAuthTag()]);
  return { iv: iv.toString("base64"), data: data.toString("base64") };
};

const decrypt = (key, lookupId, record) => {
  const raw = Buffer.from(record.data, "base64");
  const decipher = createDecipheriv("aes-256-gcm", key, Buffer.from(record.iv, "base64"));
  decipher.setAAD(Buffer.from(lookupId));
  decipher.setAuthTag(raw.subarray(raw.length - 16));
  return JSON.parse(Buffer.concat([decipher.update(raw.subarray(0, raw.length - 16)), decipher.final()]).toString("utf8"));
};

const newCertNo = (prefix) => {
  const chars = Array.from({ length: 12 }, () => CROCKFORD[randomInt(CROCKFORD.length)]).join("");
  return `${prefix}-${chars.slice(0, 4)}-${chars.slice(4, 8)}-${chars.slice(8)}`;
};

const isDate = (value) => /^\d{4}-\d{2}-\d{2}$/.test(value) && !Number.isNaN(new Date(`${value}T00:00:00Z`).getTime());

const verifyLink = (args, certNo) => {
  const base = (args["base-url"] || process.env.CERT_VERIFY_BASE_URL || "").replace(/\/+$/, "");
  return `${base}/verify?id=${encodeURIComponent(certNo)}`;
};

const issue = (registry, args, { name, course, completed, id }) => {
  name = String(name || "").trim();
  course = String(course || "").trim();
  completed = String(completed || "").trim();
  if (!name) fail("missing --name");
  if (!course) fail("missing --course");
  if (!isDate(completed)) fail(`--completed must be a date like 2026-11-01 (got "${completed}")`);
  const certNo = id ? String(id).trim().toUpperCase() : newCertNo(args.prefix || "U7K");
  const { lookupId, key } = deriveKeys(registry, certNo);
  if (registry.records[lookupId]) fail(`certificate ${certNo} already exists`);
  const details = { id: certNo, name, course, completed, issued: new Date().toISOString().slice(0, 10), status: "valid" };
  registry.records[lookupId] = encrypt(key, lookupId, details);
  return certNo;
};

const parseCsv = (text) => {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field); field = "";
      if (row.some((cell) => cell.trim() !== "")) rows.push(row);
      row = [];
    } else field += ch;
  }
  row.push(field);
  if (row.some((cell) => cell.trim() !== "")) rows.push(row);
  return rows;
};

const csvCell = (value) => (/[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value);

const args = parseArgs(process.argv.slice(2));
const command = args._[0];
const registry = loadRegistry();

switch (command) {
  case "add": {
    const certNo = issue(registry, args, { name: args.name, course: args.course, completed: args.completed, id: args.id });
    saveRegistry(registry);
    console.log(`Issued ${certNo}`);
    console.log(`Verify: ${verifyLink(args, certNo)}`);
    break;
  }
  case "import": {
    const file = args._[1];
    if (!file || !existsSync(file)) fail("give the path to a CSV file with columns name,course,completed[,id]");
    const absolute = resolve(file);
    if (!relative(ROOT, absolute).startsWith("..")) fail("keep the roster CSV outside this repository so participant names are never committed");
    const rows = parseCsv(readFileSync(absolute, "utf8"));
    const header = rows.shift().map((cell) => cell.trim().toLowerCase());
    const col = (name) => header.indexOf(name);
    if (col("name") < 0 || col("course") < 0 || col("completed") < 0) fail("CSV header must include name, course and completed");
    const out = [["id", "name", "course", "completed", "verify_url"]];
    for (const row of rows) {
      const entry = { name: row[col("name")], course: row[col("course")], completed: row[col("completed")], id: col("id") >= 0 ? row[col("id")] : "" };
      const certNo = issue(registry, args, entry);
      out.push([certNo, entry.name.trim(), entry.course.trim(), entry.completed.trim(), verifyLink(args, certNo)]);
    }
    saveRegistry(registry);
    const outPath = join(dirname(absolute), `${basename(absolute, extname(absolute))}.issued.csv`);
    writeFileSync(outPath, out.map((r) => r.map(csvCell).join(",")).join("\n") + "\n");
    console.log(`Issued ${out.length - 1} certificates. Numbers written to ${outPath}`);
    break;
  }
  case "revoke": {
    if (!args.id) fail("missing --id");
    const { lookupId, key } = deriveKeys(registry, args.id);
    const record = registry.records[lookupId];
    if (!record) fail(`no certificate ${args.id}`);
    const details = decrypt(key, lookupId, record);
    details.status = "revoked";
    details.revoked = new Date().toISOString().slice(0, 10);
    registry.records[lookupId] = encrypt(key, lookupId, details);
    saveRegistry(registry);
    console.log(`Revoked ${details.id} (${details.name})`);
    break;
  }
  case "check": {
    if (!args.id) fail("missing --id");
    const { lookupId, key } = deriveKeys(registry, args.id);
    const record = registry.records[lookupId];
    if (!record) fail(`no certificate ${args.id}`);
    console.log(JSON.stringify(decrypt(key, lookupId, record), null, 2));
    break;
  }
  case "init": {
    if (existsSync(REGISTRY_PATH)) fail("registry already exists");
    saveRegistry(registry);
    console.log(`Created ${relative(ROOT, REGISTRY_PATH)}`);
    break;
  }
  case "count": {
    console.log(`${Object.keys(registry.records).length} certificates in the registry`);
    break;
  }
  default:
    console.log(readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n").slice(1, 20).map((l) => l.replace(/^\/\/ ?/, "")).join("\n"));
    process.exit(command ? 1 : 0);
}
